package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"regexp"
	"strings"

	"calyx/vb6tools/internal/vbfile"
)

// vbaJSONSHA256 is the hash of third_party/vba-json/JsonConverter.bas (VBA-JSON v2.3.1). A
// changed file must be reviewed before the rename list below is trusted again.
const vbaJSONSHA256 = "1c240aa3c7ef536c25bf44061b02b0fadeb39bfb449f67c419822650e23f6169"

// renames covers every public name of VBA-JSON v2.3.1. The Calyx prefix keeps them apart from
// the names of the ERP, which may have its own copy of VBA-JSON.
var renames = map[string]string{
	"JsonOptions":   "CalyxJsonOptions",
	"ParseJson":     "CalyxParseJson",
	"ConvertToJson": "CalyxConvertToJson",
	"ParseUtc":      "CalyxParseUtc",
	"ConvertToUtc":  "CalyxConvertToUtc",
	"ParseIso":      "CalyxParseIso",
	"ConvertToIso":  "CalyxConvertToIso",
}

const generatedJSONNote = "' Generated by vb6gen from third_party/vba-json/JsonConverter.bas (VBA-JSON v2.3.1). Do not edit."

// publicName finds the first name that a module-level line declares as public. A Declare,
// Function, Sub, Property, Type or Enum without Public or Private is public too.
var publicName = regexp.MustCompile(`(?i)^\s*(?:(?:Public|Global)\s+(?:WithEvents\s+|Static\s+)?(?:(?:Function|Sub|Property\s+(?:Get|Let|Set)|Const|Enum|Type|Declare\s+(?:PtrSafe\s+)?(?:Function|Sub))\s+)?|(?:Static\s+)?(?:Declare\s+(?:PtrSafe\s+)?)?(?:Function|Sub|Property\s+(?:Get|Let|Set)|Enum|Type)\s+)(\w+)`)

// variableList finds the part after Public or Global that can hold several names.
var variableList = regexp.MustCompile(`(?i)^\s*(?:Public|Global)\s+(?:WithEvents\s+)?(?:Const\s+)?(.*)$`)

// procedureWord starts a declaration that has one name only.
var procedureWord = regexp.MustCompile(`(?i)^(?:Static|Function|Sub|Property|Enum|Type|Declare)\b`)

func checkSHA256(src []byte) error {
	sum := sha256.Sum256(src)
	if got := hex.EncodeToString(sum[:]); got != vbaJSONSHA256 {
		return fmt.Errorf("JsonConverter.bas: SHA-256 is %s, want %s", got, vbaJSONSHA256)
	}
	return nil
}

// buildJSON returns CalyxJson.bas from the pinned VBA-JSON file.
func buildJSON(src []byte) (vbfile.File, error) {
	if err := checkSHA256(src); err != nil {
		return vbfile.File{}, err
	}
	return transformJSON(src)
}

// transformJSON renames the module and the public names. The original comments, with the
// license notice, stay where they are.
func transformJSON(src []byte) (vbfile.File, error) {
	lines := strings.Split(strings.ReplaceAll(string(src), "\r\n", "\n"), "\n")
	if lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}

	var attrs []string
	named := false
	for len(lines) > 0 && strings.HasPrefix(lines[0], "Attribute ") {
		if strings.HasPrefix(lines[0], "Attribute VB_Name ") {
			attrs = append(attrs, `Attribute VB_Name = "CalyxJson"`)
			named = true
		} else {
			attrs = append(attrs, lines[0])
		}
		lines = lines[1:]
	}
	if !named {
		return vbfile.File{}, fmt.Errorf("JsonConverter.bas: no Attribute VB_Name line")
	}

	if err := checkPublicNames(lines); err != nil {
		return vbfile.File{}, err
	}

	body := []string{generatedJSONNote}
	for _, l := range lines {
		body = append(body, renameLine(l))
	}
	return vbfile.File{Attributes: attrs, Body: body}, nil
}

func checkPublicNames(lines []string) error {
	var missing []string
	for _, l := range lines {
		for _, name := range publicNames(l) {
			if _, ok := lookupRename(name); !ok {
				missing = append(missing, name)
			}
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("JsonConverter.bas: public names not in the rename list of vb6gen: %s", strings.Join(missing, ", "))
	}
	return nil
}

// publicNames returns every public name of one module-level line. "Public A As Long, B As Long"
// and "Public Const A = 1, B = 2" declare more than one name.
func publicNames(line string) []string {
	m := publicName.FindStringSubmatch(line)
	if m == nil {
		return nil
	}
	names := []string{m[1]}
	rest := variableList.FindStringSubmatch(line)
	if rest == nil || procedureWord.MatchString(rest[1]) {
		return names
	}
	for _, part := range splitDeclaration(rest[1])[1:] {
		if w := strings.Fields(part); len(w) > 0 {
			names = append(names, identifierAt(w[0]))
		}
	}
	return names
}

// identifierAt returns the leading identifier of s, for example "Arr" from "Arr(1".
func identifierAt(s string) string {
	end := 0
	for end < len(s) && isIdentPart(s[end]) {
		end++
	}
	return s[:end]
}

// splitDeclaration splits on the commas of the declaration itself. It ignores commas inside
// parentheses and strings, and it stops at a comment.
func splitDeclaration(s string) []string {
	var parts []string
	depth, start, inStr := 0, 0, false
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '"':
			inStr = !inStr
		case inStr:
		case c == '\'':
			return append(parts, s[start:i])
		case c == '(':
			depth++
		case c == ')':
			depth--
		case c == ',' && depth == 0:
			parts = append(parts, s[start:i])
			start = i + 1
		}
	}
	return append(parts, s[start:])
}

// lookupRename ignores letter case, as VB6 does for names.
func lookupRename(name string) (string, bool) {
	for from, to := range renames {
		if strings.EqualFold(from, name) {
			return to, true
		}
	}
	return "", false
}

// renameLine renames whole identifiers in the code part of one line. Text inside a string or
// a comment does not change, because it is not a use of the name.
func renameLine(line string) string {
	var b strings.Builder
	inString := false
	for i := 0; i < len(line); {
		c := line[i]
		switch {
		case c == '"':
			// A doubled quote inside a string closes and opens it again, so this toggle is enough.
			inString = !inString
			b.WriteByte(c)
			i++
		case inString:
			b.WriteByte(c)
			i++
		case c == '\'':
			b.WriteString(line[i:])
			return b.String()
		case isIdentStart(c):
			j := i + 1
			for j < len(line) && isIdentPart(line[j]) {
				j++
			}
			word := line[i:j]
			if to, ok := lookupRename(word); ok {
				word = to
			}
			b.WriteString(word)
			i = j
		default:
			b.WriteByte(c)
			i++
		}
	}
	return b.String()
}

func isIdentStart(c byte) bool {
	return c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z'
}

func isIdentPart(c byte) bool {
	return isIdentStart(c) || c >= '0' && c <= '9' || c == '_'
}
