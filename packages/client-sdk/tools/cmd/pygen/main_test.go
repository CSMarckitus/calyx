var update = flag.Bool("update", false, "write the files of testdata/golden again")

// toolsDir is the tools module root, seen from this package folder.
const toolsDir = "../.."

const goldenDir = "testdata/golden"

func loadSpec(t *testing.T) *spec.Doc {
	t.Helper()
	in := inputPaths(toolsDir)
	doc, err := spec.Load(in.openAPI, in.advice, in.createCalls)
	if err != nil {
		t.Fatal(err)
	}
	return doc
}

func build(t *testing.T) map[string][]byte {
	t.Helper()
	files, err := buildFiles(loadSpec(t))
	if err != nil {
		t.Fatal(err)
	}
	return files
}

// TestGoldenFiles compares each generated file with its golden file, in both directions.
func TestGoldenFiles(t *testing.T) {
	files := build(t)
	if *update {
		if err := genfiles.Write(files, goldenDir, ".py"); err != nil {
			t.Fatal(err)
		}
	}
	stale, err := genfiles.Compare(files, goldenDir, ".py")
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) > 0 {
		t.Fatalf("these files differ from testdata/golden: %v; run go test ./cmd/pygen -update and review the diff", stale)
	}
}

func TestEveryFileHasTheHeader(t *testing.T) {
	for name, content := range build(t) {
		if !bytes.HasPrefix(content, []byte("# Code generated by pygen. DO NOT EDIT.\n")) {
			t.Errorf("%s does not start with the header", name)
		}
	}
}

// The codes and the advice of the Python files are the rows of retry-advice.json, in both
// directions: no row is missing, and no line is extra.
func TestCodesAndAdviceAreTheRows(t *testing.T) {
	files := build(t)
	wantCodes := map[string][]string{}
	var wantAdvice []string
	for _, r := range loadSpec(t).Advice {
		wantCodes[r.Source] = append(wantCodes[r.Source], r.Code)
		wantAdvice = append(wantAdvice, fmt.Sprintf(`    (%q, %q): %q,`, r.Source, r.Code, r.Retry))
	}

	gotCodes := map[string][]string{}
	source := ""
	for line := range strings.Lines(string(files["codes.py"])) {
		if strings.HasPrefix(line, "class ") {
			class := strings.TrimSuffix(strings.TrimPrefix(line, "class "), "Code:\n")
			source = strings.ToLower(class)
		}
		if _, value, ok := strings.Cut(line, ": Final = "); ok {
			gotCodes[source] = append(gotCodes[source], strings.Trim(value, "\"\n"))
		}
	}
	if !maps.EqualFunc(gotCodes, wantCodes, slices.Equal) {
		t.Errorf("codes.py: got %v, want %v", gotCodes, wantCodes)
	}

	var gotAdvice []string
	for line := range strings.Lines(string(files["advice.py"])) {
		if strings.HasPrefix(line, "    ") {
			gotAdvice = append(gotAdvice, strings.TrimSuffix(line, "\n"))
		}
	}
	slices.Sort(gotAdvice)
	slices.Sort(wantAdvice)
	if !slices.Equal(gotAdvice, wantAdvice) {
		t.Errorf("advice.py: got %v, want %v", gotAdvice, wantAdvice)
	}
}

func TestConstantNames(t *testing.T) {
	for code, want := range map[string]string{
		"not_found":                        "NOT_FOUND",
		"UNAVAILABLE":                      "UNAVAILABLE",
		"ERROR_REASON_SEND_IN_PROGRESS":    "SEND_IN_PROGRESS",
		"ERROR_REASON_INSTANCE_QUEUE_FULL": "INSTANCE_QUEUE_FULL",
	} {
		if got := constantName(code); got != want {
			t.Errorf("%s: got %s, want %s", code, got, want)
		}
	}
}

func TestFailsOnCodeWithNoUniqueConstantName(t *testing.T) {
	for _, code := range []string{
		"ERROR_REASON_NOT_FOUND", // the core also has NOT_FOUND
		"ERROR_REASON_",
		"has-hyphen",
		`ends_with_"`,
		"9_lives",
		"two\nlines",
	} {
		doc := loadSpec(t)
		doc.Advice = append(doc.Advice, spec.AdviceRow{Source: "core", Code: code, Retry: "unknown"})
		_, err := buildFiles(doc)
		if err == nil || !strings.Contains(err.Error(), fmt.Sprintf("%q", code)) {
			t.Errorf("%q: want an error that names the code, got %v", code, err)
		}
	}
}

// Python reads each result as the same text. An escape of Go has the same meaning in Python.
func TestPythonStrings(t *testing.T) {
	for text, want := range map[string]string{
		`plain`:               `"plain"`,
		`ends with "`:         `"ends with \""`,
		`it's`:                `"it's"`,
		`back\slash\`:         `"back\\slash\\"`,
		"line\nnext\tand\x00": `"line\nnext\tand\x00"`,
		"\u2028":              `"\u2028"`,
	} {
		if got := pythonString(text); got != want {
			t.Errorf("%q: got %s, want %s", text, got, want)
		}
	}
}

func TestRunWritesAndChecks(t *testing.T) {
	in := inputPaths(toolsDir)
	out := filepath.Join(t.TempDir(), "_generated")
	pygen := func(extra ...string) (int, string) {
		t.Helper()
		var messages bytes.Buffer
		args := []string{"-openapi", in.openAPI, "-advice", in.advice, "-create-calls", in.createCalls, "-out", out}
		return run(append(args, extra...), &messages), messages.String()
	}

	if code, text := pygen("-check"); code != 1 || !strings.Contains(text, "codes.py is out of date") {
		t.Errorf("check with no folder: got %d, %q; want 1 and the name of the file", code, text)
	}
	if _, err := os.Stat(out); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("-check wrote the output folder: %v", err)
	}
	if code, text := pygen(); code != 0 || text != "" {
		t.Errorf("write: got %d, %q; want 0 and no text", code, text)
	}
	if code, text := pygen("-check"); code != 0 || text != "" {
		t.Errorf("check after write: got %d, %q; want 0 and no text", code, text)
	}
	if code, text := pygen("-advice", "no-such-file.json"); code != 2 || !strings.Contains(text, "no-such-file.json") {
		t.Errorf("missing input: got %d, %q; want 2 and the name of the file", code, text)
	}
}
